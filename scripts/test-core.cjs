const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
function storage() { const data = new Map(); return { getItem:k => data.get(k) || null, setItem:(k,v) => data.set(k,String(v)), removeItem:k => data.delete(k) }; }
const context = { window:{WIKI_CONFIG:{}}, URL, URLSearchParams, crypto:require('node:crypto').webcrypto, structuredClone, localStorage:storage(), sessionStorage:storage(), location:{hash:''} };
vm.createContext(context);
for (const file of ['features.js','remote-import.js','store.js']) vm.runInContext(fs.readFileSync(file,'utf8'),context);
const features = context.window.wikiFeatures, db = context.window.wikiStore;
(async () => {
  assert.equal(features.ticketUrl(features.glpiDefault,8487),'https://helpdesk.hmru.ru:8080/front/ticket.form.php?id=8487');
  for(const bad of ['javascript:alert({id})','https://u:p@example.com/?id={id}','https://example.com/no-id','https://example.com/{id}/{id}']) assert.throws(() => features.validateGlpiTemplate(bad));
  assert.equal(features.ticketUrl(features.glpiDefault,'8487&x=bad'),'');
  assert.deepEqual(Array.from(features.parseTags('Windows, печать, windows')),['windows','печать']);
  assert.deepEqual(Array.from(features.parseTickets('#8487, 8490,8487')),[8487,8490]);
  assert.throws(() => features.parseTickets('8487,abc'));
  assert.throws(() => features.parseTickets('9007199254740992'));
  assert.equal(features.templateBlocks('troubleshooting').length,8);
  assert.equal(features.templateBlocks('blank').length,0);
  const changes = features.versionChanges({title:'Было',blocks:[{type:'text',text:'Старый текст'}]}, {title:'Стало',blocks:[{type:'text',text:'Новый текст'},{type:'image',path:'photo'}]});
  assert.equal(changes.length,3);
  assert.equal(changes[0].field,'title');
  assert.equal(changes[1].before.text,'Старый текст');
  assert.equal(changes[1].after.text,'Новый текст');
  assert.equal(changes[2].before,null);
  assert.equal(features.versionChanges({blocks:[{type:'text',text:'x',client_id:'a'}]}, {blocks:[{type:'text',text:'x',client_id:'b'}]}).length,0);
  assert.equal(features.versionChanges({publication_state:'draft'}, {publication_state:'published'})[0].field,'publication_state');
  const imp=context.window.wikiImport;
  assert.equal(features.remoteConnections({tool:'AnyDesk',remote_id:'123',remote_connections:[{tool:'AnyDesk',remote_id:'old'},{tool:'RuDesktop',remote_id:'456'}]}).length,2);
  assert.equal(features.remoteConnections({tool:'AnyDesk',remote_id:'123'})[0].remote_id,'123');
  const parsed=imp.parseText('Имя;ID;Программа\n"ПК; склад";123 456;RuDesktop\nОфис;987;AnyDesk');
  assert.equal(parsed[1][0],'ПК; склад');assert.equal(parsed[1][1],'123 456');assert.equal(imp.mapping(parsed[0]).remote_id,1);
  assert.equal(imp.parseText('Name\tID\nOffice\t123')[1][1],'123');
  assert.equal(imp.program('рудесктоп'),'RuDesktop');assert.equal(imp.program('Неизвестная'),'');
  await db.init();
  const id = context.crypto.randomUUID();
  const item = { id, type:'knowledge', title:'Feature test', summary:'', section_id:null, visibility:'all', blocks:features.templateBlocks('instruction'), device:'',tool:'',remote_id:'', pinned:true,tags:['windows'],publication_state:'draft',relevance:'review',glpi_ticket_ids:[8487],related_ids:[db.entries[0].id] };
  await db.saveEntry(item);
  await db.patchEntry(id,{publication_state:'published'});
  await db.saveComment(id,'  Article comment  ');
  const comment = (await db.commentsFor(id))[0];
  assert.equal(comment.body,'Article comment');
  await db.deleteEntry(id);
  assert(db.entries.find(e => e.id===id).deleted_at);
  assert.equal((await db.commentsFor(id)).length,1);
  await db.restoreEntry(id);
  const restored = db.entries.find(e => e.id===id);
  assert.equal(restored.deleted_at,null);
  assert.equal(restored.pinned,true);
  assert.equal(restored.glpi_ticket_ids[0],8487);
  assert.equal(restored.related_ids.length,1);
  await db.saveComment(id,'Updated',comment.id);
  assert.equal((await db.commentsFor(id))[0].body,'Updated');
  db.role='reader'; db.user={id:'other'};
  await assert.rejects(() => db.patchEntry(id,{pinned:false}),/Недостаточно прав/);
  await assert.rejects(() => db.deleteComment(comment.id),/Недостаточно прав/);
  await assert.rejects(() => db.saveComment(id,'Hijacked',comment.id),/Недостаточно прав/);
  db.role='admin'; db.user=null;
  await db.deleteComment(comment.id);
  assert.equal((await db.commentsFor(id)).length,0);
  const exported = db.exportLocal();
  assert(exported.settings.glpi_ticket_url_template.includes('{id}'));
  const purgeId = context.crypto.randomUUID();
  await db.saveEntry({...item,id:purgeId});
  await assert.rejects(()=>db.purgeEntry(purgeId), /корзины/);
  await db.deleteEntry(purgeId);
  await db.saveComment(id,'Remain');
  await db.purgeEntry(purgeId);
  assert(!db.entries.some(e=>e.id===purgeId));
  assert(!db.history.some(e=>e.entry_id===purgeId));
  console.log('PASS: GLPI safety, metadata parsing, templates, drafts, trash preservation and comment ownership');
})().catch(e => { console.error(e); process.exitCode=1; });
